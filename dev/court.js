import * as THREE from 'three';
import { buildCourt, buildUmpireChair } from '../src/world/court.js';
import { buildArena } from '../src/world/arena.js';
const q = new URLSearchParams(location.search);
const W = +q.get('w') || innerWidth, H = +q.get('h') || innerHeight;
const renderer = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
renderer.setSize(W, H); renderer.setPixelRatio(1); renderer.shadowMap.enabled = true; renderer.shadowMap.type = THREE.PCFSoftShadowMap;
renderer.toneMapping = THREE.ACESFilmicToneMapping; renderer.toneMappingExposure = 1.05; renderer.outputColorSpace = THREE.SRGBColorSpace;
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene(); scene.background = new THREE.Color(0x070a18);
const t0 = performance.now();
const arena = buildArena({ quality: q.get('quality') || 'medium' }); scene.add(arena.group);
const court = buildCourt(); scene.add(court.group);
const chair = buildUmpireChair(); chair.position.set(4.3, 0, 0); chair.rotation.y = -Math.PI / 2; scene.add(chair);
arena.anim.update(0.1, 0.3);
document.getElementById('log').textContent = `built ${(performance.now() - t0).toFixed(0)}ms`;
const cam = new THREE.PerspectiveCamera(+q.get('fov') || 42, W / H, 0.1, 200);
cam.position.set(+q.get('cx') || 0, +q.get('cy') || 8.2, +q.get('cz') || 17); cam.lookAt(+q.get('lx') || 0, +q.get('ly') || 0.6, +q.get('lz') || -1.5);
renderer.render(scene, cam);
window.__ready = true; window.__info = document.getElementById('log').textContent;
